package com.xwiki.licensing.internal.issuing;

import java.util.ArrayDeque;
import java.util.Collections;
import java.util.LinkedHashSet;
import java.util.Optional;
import java.util.Queue;
import java.util.Set;

import javax.inject.Inject;
import javax.inject.Singleton;

import org.apache.commons.lang3.StringUtils;
import org.slf4j.Logger;
import org.xwiki.component.annotation.Component;
import org.xwiki.extension.DefaultExtensionDependency;
import org.xwiki.extension.Extension;
import org.xwiki.extension.ExtensionDependency;
import org.xwiki.extension.ExtensionId;
import org.xwiki.extension.ExtensionManager;
import org.xwiki.extension.ResolveException;
import org.xwiki.extension.repository.ExtensionRepositoryManager;
import org.xwiki.extension.version.Version;
import org.xwiki.extension.version.internal.DefaultVersionConstraint;

/**
 * Computes the paid dependencies covered by the license of a feature. It is a port of the
 * {@code #getLicensedExtension}, {@code #setExtraLicenseDetails} and {@code #getDependentFeatureIds} macros of
 * {@code License.Code.LicenseDetailsMacros}, which Sales uses: the result must stay the same, so that a license
 * issued through the API covers exactly what a license generated by Sales would.
 *
 * @version $Id$
 * @since 1.34
 */
@Component(roles = LicensedDependencyResolver.class)
@Singleton
public class LicensedDependencyResolver
{
    /**
     * The extension that paid extensions depend on directly.
     */
    static final String LICENSOR_ID = "com.xwiki.licensing:application-licensing-licensor-api";

    /**
     * The extension property naming a package whose paid modules are covered by the license too.
     */
    static final String PACKAGE_ID_PROPERTY = "xwiki.extension.licensing.packageId";

    /**
     * The extension property giving the version of that package.
     */
    static final String PACKAGE_VERSION_PROPERTY = "xwiki.extension.licensing.packageVersion";

    /**
     * Only these dependencies are walked, to speed up the search: paid extensions are all published by XWiki SAS.
     */
    static final String WALKED_PREFIX = "com.xwiki.";

    /**
     * The macro can't write a "while" loop, so it analyzes at most this many dependencies ({@code [0..1000]}).
     */
    static final int MAX_STEPS = 1001;

    @Inject
    private Logger logger;

    @Inject
    private ExtensionManager extensionManager;

    @Inject
    private ExtensionRepositoryManager repositoryManager;

    @Inject
    private ApiConfiguration configuration;

    /**
     * The licensed dependencies of a feature.
     *
     * @version $Id$
     */
    public static final class LicensedDependencies
    {
        private final String extensionVersion;

        private final Set<String> dependentFeatureIds;

        LicensedDependencies(String extensionVersion, Set<String> dependentFeatureIds)
        {
            this.extensionVersion = extensionVersion;
            this.dependentFeatureIds = Collections.unmodifiableSet(dependentFeatureIds);
        }

        /**
         * @return the version of the feature the dependencies were computed for
         */
        public String getExtensionVersion()
        {
            return this.extensionVersion;
        }

        /**
         * @return the paid extensions the feature depends on, which the license covers too
         */
        public Set<String> getDependentFeatureIds()
        {
            return this.dependentFeatureIds;
        }
    }

    /**
     * @param featureId the licensed feature
     * @param extensionVersion the version of the feature, or {@code null} to use the latest stable version
     * @return the licensed dependencies, or empty if the feature can't be resolved (unknown feature, no stable
     *     version)
     */
    public Optional<LicensedDependencies> resolve(String featureId, String extensionVersion)
    {
        // #getLicensedExtension
        String version = StringUtils.isEmpty(extensionVersion) ? getLatestStableVersion(featureId) : extensionVersion;
        if (version == null) {
            return Optional.empty();
        }
        Extension extension = resolve(new ExtensionId(featureId, version));
        if (extension == null) {
            return Optional.empty();
        }

        // #setExtraLicenseDetails
        Set<String> dependentFeatureIds = new LinkedHashSet<>();
        String packageId = getProperty(extension, PACKAGE_ID_PROPERTY);
        if (packageId != null) {
            String packageVersion = getProperty(extension, PACKAGE_VERSION_PROPERTY);
            if (packageVersion == null) {
                packageVersion = extension.getId().getVersion().getValue();
            }
            Extension licensedPackage = resolve(new ExtensionId(packageId, packageVersion));
            if (licensedPackage != null) {
                // Add the paid modules of the package.
                collectLicensedDependencies(licensedPackage, dependentFeatureIds);
            }
        }
        // Add the paid modules that are transitive dependencies.
        collectLicensedDependencies(extension, dependentFeatureIds);

        return Optional.of(new LicensedDependencies(version, dependentFeatureIds));
    }

    /**
     * Port of {@code #getDependentFeatureIds}: a breadth-first walk of the non optional {@code com.xwiki.*}
     * dependencies, collecting those that depend directly (and not optionally) on the licensor.
     */
    private void collectLicensedDependencies(Extension extension, Set<String> dependentFeatureIds)
    {
        String namespace = "wiki:" + this.configuration.getMainWiki().getName();
        Queue<ExtensionDependency> dependencies = new ArrayDeque<>();
        dependencies.add(new DefaultExtensionDependency(extension.getId().getId(),
            new DefaultVersionConstraint(extension.getId().getVersion().getValue())));
        for (int i = 0; i < MAX_STEPS; i++) {
            ExtensionDependency dependency = dependencies.poll();
            if (dependency == null) {
                break;
            }
            if (!dependency.isOptional()) {
                Extension resolvedDependency = resolve(dependency, namespace);
                if (resolvedDependency != null) {
                    for (ExtensionDependency childDependency : resolvedDependency.getDependencies()) {
                        if (LICENSOR_ID.equals(childDependency.getId()) && !childDependency.isOptional()) {
                            dependentFeatureIds.add(resolvedDependency.getId().getId());
                        } else if (childDependency.getId().startsWith(WALKED_PREFIX)) {
                            dependencies.add(childDependency);
                        }
                    }
                }
            }
        }
        dependentFeatureIds.remove(extension.getId().getId());
    }

    private String getLatestStableVersion(String featureId)
    {
        String latest = null;
        try {
            // The versions are returned in ascending order.
            for (Version version : this.repositoryManager.resolveVersions(featureId, 0, -1)) {
                if (version.getType() == Version.Type.STABLE) {
                    latest = version.getValue();
                }
            }
        } catch (ResolveException e) {
            this.logger.warn("Failed to resolve the versions of [{}]: {}", featureId, e.getMessage());
        }
        return latest;
    }

    private Extension resolve(ExtensionId extensionId)
    {
        try {
            return this.extensionManager.resolveExtension(extensionId);
        } catch (ResolveException e) {
            this.logger.warn("Failed to resolve [{}]: {}", extensionId, e.getMessage());
            return null;
        }
    }

    private Extension resolve(ExtensionDependency dependency, String namespace)
    {
        try {
            return this.extensionManager.resolveExtension(dependency, namespace);
        } catch (ResolveException e) {
            this.logger.debug("Failed to resolve the dependency [{}]: {}", dependency, e.getMessage());
            return null;
        }
    }

    private static String getProperty(Extension extension, String key)
    {
        Object value = extension.getProperty(key);
        return value == null ? null : StringUtils.defaultIfEmpty(value.toString(), null);
    }
}
